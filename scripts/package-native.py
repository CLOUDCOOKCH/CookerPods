#!/usr/bin/env python3
"""Publish self-contained Windows previews and package runtime notices/checksums."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
from zipfile import ZIP_DEFLATED, ZipFile

root = Path(__file__).resolve().parent.parent
parser = argparse.ArgumentParser()
parser.add_argument('--rid', choices=['win-x64', 'win-arm64'], action='append')
args = parser.parse_args()
rids = args.rid or ['win-x64', 'win-arm64']
dotnet = str(Path(os.environ['DOTNET_ROOT']) / ('dotnet.exe' if os.name == 'nt' else 'dotnet')) if 'DOTNET_ROOT' in os.environ else shutil.which('dotnet')
if not dotnet:
    raise SystemExit('A supported .NET SDK is needed by developers; preview downloads include the runtime for end users.')
output = root / 'artifacts' / 'native'
output.mkdir(parents=True, exist_ok=True)
nuget_output = subprocess.check_output([dotnet, 'nuget', 'locals', 'global-packages', '--list', '--force-english-output'], text=True)
nuget_root = Path(nuget_output.strip().split(': ', 1)[1])
checksums = []
for rid in rids:
    stage = output / rid
    # This directory contains only disposable outputs generated by this script.
    if stage.exists():
        shutil.rmtree(stage)
    subprocess.run([dotnet, 'publish', str(root / 'native/CookerPods.Diagnostic.Windows'),
        '-c', 'Release', '-r', rid, '--self-contained', 'true',
        '-p:PublishSingleFile=true', '-p:IncludeNativeLibrariesForSelfExtract=true',
        '-p:PublishTrimmed=false', '-p:RestoreLockedMode=true', '-m:2',
        '--output', str(stage), '--verbosity', 'minimal'], cwd=root, check=True)
    assets = json.loads((root / 'native/CookerPods.Diagnostic.Windows/obj/project.assets.json').read_text())
    downloads = [item for framework in assets['project']['frameworks'].values() for item in framework.get('downloadDependencies', [])]
    runtime = next(d for d in downloads if d['name'].lower() == f'microsoft.netcore.app.runtime.{rid}')
    runtime_version = runtime['version'].strip('[] ').split(',')[0].strip()
    pack = nuget_root / runtime['name'].lower() / runtime_version
    for name in ['LICENSE.TXT', 'THIRD-PARTY-NOTICES.TXT']:
        shutil.copyfile(pack / name, stage / ('DOTNET-' + name))
    shutil.copyfile(root / 'LICENSE', stage / 'LICENSE-CookerPods.txt')
    shutil.copyfile(root / 'native/THIRD_PARTY_NOTICES.md', stage / 'THIRD_PARTY_NOTICES.md')
    shutil.copyfile(root / 'docs/native-windows.md', stage / 'README.md')
    commit = subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=root, text=True).strip()
    dirty = bool(subprocess.check_output(['git', 'status', '--porcelain'], cwd=root, text=True).strip())
    metadata = {'version': '0.4.0-native-preview', 'rid': rid, 'sdk': subprocess.check_output([dotnet, '--version'], cwd=root, text=True).strip(), 'runtime': runtime_version, 'sourceCommit': commit if not dirty else None, 'sourceState': 'committed' if not dirty else 'uncommitted development build', 'signature': 'unsigned development preview', 'hardwareValidated': False}
    (stage / 'BUILDINFO.json').write_text(json.dumps(metadata, indent=2), encoding='utf-8')
    archive = output / f'CookerPods-Diagnostic-0.4.0-preview-{rid}.zip'
    with ZipFile(archive, 'w', ZIP_DEFLATED, compresslevel=9) as bundle:
        for file in sorted(stage.iterdir()):
            if file.is_file() and file.suffix.lower() != '.pdb':
                bundle.write(file, file.name)
    with ZipFile(archive) as bundle:
        if bundle.testzip() is not None or 'CookerPods-Diagnostic.exe' not in bundle.namelist():
            raise SystemExit('Package integrity check failed')
    with archive.open('rb') as file:
        checksum = hashlib.file_digest(file, 'sha256').hexdigest()
    checksums.append(f'{checksum}  {archive.name}')
    print(f'Packaged {archive.name}: {archive.stat().st_size:,} bytes')
(output / 'SHA256SUMS.txt').write_text('\n'.join(checksums) + '\n', encoding='ascii')
